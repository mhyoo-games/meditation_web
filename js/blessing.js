export function fortuneFor(name, date = new Date()) {
  const d = `${date.getFullYear()}-${date.getMonth() + 1}-${date.getDate()}`;
  const r = rng(hash(name.trim() + '|' + d)); const pick = a => a[Math.floor(r() * a.length)];
  const stars = 3 + Math.floor(r() * 3);
  return { stars, luck: LUCK[stars - 1 + Math.floor(r() * 2)] || LUCK[4], text: pick(GENERAL), word: pick(WORDS), color: pick(COLORS), item: pick(ITEMS), number: 1 + Math.floor(r() * 9) };
}
